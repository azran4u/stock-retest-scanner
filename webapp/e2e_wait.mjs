// WAIT status ('ממתינה לסגירה': healthy red last week on above-average volume) smoke test, demo mode. Usage: node e2e_wait.mjs [baseURL] [outDir]
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const BASE = process.argv[2] || 'http://localhost:4173/stock-retest-scanner/app/';
const OUT = process.argv[3] || '/workspace/app_shots';
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true, locale: 'he-IL' });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const ok = (c, m) => { if (!c) { console.log('FAIL', m); process.exitCode = 1; } else console.log('ok  ', m); };
await page.goto(BASE + '?demo=1');
await page.waitForSelector('.row');
ok(await page.locator('.fi[data-f="st_wait"]').count() === 1, 'WAIT filter exists');
await page.evaluate(() => window.__srs.setChip('waiting')); await page.waitForTimeout(300);
const n = await page.locator('.row').count();
ok(n > 0, `waiting chip: ${n} rows`);
ok(await page.locator('.row .b-wait').count() >= n, 'every row has the ממתינה לסגירה badge');
const why = await page.locator('.row .wait-why').first().textContent();
ok(/נר אדום .*מחזור .*× ממוצע 30 יום|פטיש הפוך/.test(why || ''), `reason line: ${why}`);
ok(await page.locator('.row .b-pass').count() === 0, 'no PASS badge on waiting rows');
await page.screenshot({ path: `${OUT}/20_waiting_list.png` });
await page.locator('.row').first().click();
await page.waitForSelector('.wait-box', { timeout: 15000 });
ok(/ממתינה לסגירה שבועית/.test(await page.locator('.wait-box').textContent()), 'ticker panel explains the wait');
ok(/ממתינה לסגירה/.test(await page.locator('#tkb').textContent()), 'header badge');
await page.screenshot({ path: `${OUT}/21_waiting_ticker.png`, fullPage: true });
ok(errors.length === 0, `no page errors ${JSON.stringify(errors)}`);
await browser.close();
